import { describe, expect, it } from 'vitest'
import { stem } from './stemmer'

describe('stem — конкретные основы (по эталону Snowball)', () => {
  it.each([
    ['бесплатно', 'бесплатн'],
    ['бесплатный', 'бесплатн'],
    ['вакансии', 'ваканс'],
    ['курсы', 'курс'],
    ['ногтей', 'ногт'],
    ['диваны', 'дива'], // известная слабость Snowball — компенсируется в text.ts
    ['скачать', 'скача'],
    ['обучение', 'обучен'],
    ['красивейший', 'красив'],
    ['пушистость', 'пушист'],
    ['купаться', 'купа'],
  ])('%s → %s', (word, expected) => {
    expect(stem(word)).toBe(expected)
  })
})

describe('stem — разные формы одного слова дают одну основу', () => {
  it.each([
    [['бесплатно', 'бесплатный', 'бесплатные', 'бесплатная', 'бесплатного']],
    [['вакансия', 'вакансии', 'вакансий', 'вакансиями']],
    [['ногти', 'ногтей', 'ногтям', 'ногтями']],
    [['курс', 'курсы', 'курсов', 'курсами']],
    [['аптека', 'аптеки', 'аптеке', 'аптеку']],
    [['лосьон', 'лосьона', 'лосьоны']],
  ])('%j', (forms) => {
    const stems = new Set(forms.map(stem))
    expect(stems.size).toBe(1)
  })
})

describe('stem — особые случаи', () => {
  it('ё приравнивается к е', () => {
    expect(stem('ёлка')).toBe(stem('елка'))
  })
  it('регистр не важен', () => {
    expect(stem('БЕСПЛАТНО')).toBe('бесплатн')
  })
  it('латиница, цифры и смешанные слова не меняются', () => {
    expect(stem('hoff')).toBe('hoff')
    expect(stem('Oniksol')).toBe('oniksol')
    expect(stem('3d')).toBe('3d')
    expect(stem('б/у')).toBe('б/у')
    expect(stem('18+')).toBe('18+')
  })
  it('короткие слова не ломаются', () => {
    expect(stem('в')).toBe('в')
    expect(stem('бу')).toBe('бу')
    expect(stem('')).toBe('')
  })
})
